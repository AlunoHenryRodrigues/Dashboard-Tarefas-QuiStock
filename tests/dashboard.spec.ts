import {test,expect} from '@playwright/test';
const actual=!!process.env.QUISTOCK_TEST_XLSX;
const expected={hours:actual?'64,5 h':'6 h',demands:actual?'29':'3',first:actual?5:2,second:actual?6:2};
test('abre preenchido e oferece somente as duas páginas, sem configuração',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await expect(page.getByRole('heading',{level:1})).toHaveText('Dashboard do 1º ano.');
 await expect(page.locator('nav button')).toHaveCount(2);
 await expect(page.locator('input,select,dialog')).toHaveCount(0);
 await expect(page.getByRole('button',{name:/Importar|Atualizar Excel|Construir dashboard/})).toHaveCount(0);
 await expect(page.locator('.kpi').first().locator('strong')).toHaveText(expected.hours);
 await expect(page.locator('.kpi').nth(1).locator('strong')).toHaveText(expected.demands);
 await expect(page.locator('.ranking-row')).toHaveCount(expected.first);
 await expect(page.locator('.spotlight')).toHaveCount(4);
 await expect(page.locator('.spotlight').first()).toContainText('Quem teve mais demandas');
 await expect(page.locator('.spotlight').nth(1)).toContainText('Quem teve menos demandas');
 await expect(page.locator('.spotlight').nth(2)).toContainText('Quem registrou mais horas');
 await expect(page.locator('.spotlight').nth(3)).toContainText('Quem registrou menos horas');
 await expect(page.getByRole('status')).toContainText('As horas são parciais');
 await expect(page.locator('.recharts-bar-rectangle').first()).toBeVisible();
 expect(errors).toEqual([]);
});
test('navegação mantém as turmas separadas e funciona por URL, recarga e histórico',async({page})=>{
 await page.goto('/?turma=2ano');await expect(page.locator('.ranking-row')).toHaveCount(expected.second);
 await expect(page.locator('.kpi').first().locator('strong')).toHaveText('0 h');
 await expect(page.locator('.kpi').nth(1).locator('strong')).toHaveText('0');
 await expect(page.locator('.year-empty')).toContainText('ainda não tem demandas');
 await page.getByRole('button',{name:'Dashboard do 1º ano',exact:true}).click();
 await expect(page).toHaveURL(/turma=1ano/);await expect(page.locator('.ranking-row')).toHaveCount(expected.first);
 await expect(page.locator('.kpi').first().locator('strong')).toHaveText(expected.hours);
 await page.reload();await expect(page.locator('.kpi').first().locator('strong')).toHaveText(expected.hours);
 await page.getByRole('button',{name:'Dashboard do 2º ano',exact:true}).click();await page.goBack();
 await expect(page.getByRole('heading',{level:1})).toHaveText('Dashboard do 1º ano.');
 await expect(page.locator('.ranking-row')).toHaveCount(expected.first);
});
test('as duas páginas são legíveis no celular, sem rolagem horizontal',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/?turma=1ano');
 await expect(page.locator('.kpi').first().locator('strong')).toHaveText(expected.hours);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await expect(page.locator('.ranking-row')).toHaveCount(expected.first);
 await page.screenshot({path:'/tmp/quistock-viewer-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Dashboard do 2º ano',exact:true}).click();
 await expect(page.locator('.ranking-row')).toHaveCount(expected.second);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.setViewportSize({width:1440,height:1000});await page.getByRole('button',{name:'Dashboard do 1º ano',exact:true}).click();
 await page.screenshot({path:'/tmp/quistock-viewer-desktop.png',fullPage:true});
});
